import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { decidePublication, countConfirmedRegressions, encodeBindings, decodeBindings, type PublicationInputs } from '../ledger/publication';
import type { LedgerEvent } from '../ledger/types';
const account = (name: string, headLt: string | null = '10', headHash: string | null = 'a') => ({ account: name, headLt, headHash });
const before: PublicationInputs = { accounts: [account('owner'), account('hub')], bindings: { hub: true, unknown: false } };
assert.deepEqual(decidePublication(null, { accounts: [], bindings: {} }), { publish: true });
assert.equal(decidePublication(before, { ...before, accounts: [account('owner')] }).publish, false);
assert.equal(decidePublication(before, { ...before, accounts: [account('owner'), account('hub', '9')] }).publish, false);
assert.equal(decidePublication(before, { ...before, accounts: [account('owner'), account('hub', '10', 'different')] }).publish, false);
assert.equal(decidePublication(before, { ...before, accounts: [account('owner'), account('hub', null, null)] }).publish, false);
assert.equal(decidePublication(before, { ...before, accounts: [account('owner'), account('hub', '11')] }).publish, true);
assert.equal(decidePublication(before, { ...before, bindings: { hub: false } }).publish, false);
assert.equal(decidePublication(before, { ...before, bindings: { hub: true } }).publish, true);
assert.equal(decidePublication(before, { ...before, accounts: [...before.accounts, account('new')] }).publish, true);
const generation = randomUUID(), encoded = encodeBindings({ hub: false }, { generation, bindings: before.bindings });
assert.deepEqual(decodeBindings(encoded), { current: { hub: false }, published: { generation, bindings: before.bindings } });
assert.equal(decodeBindings({ hub: true }), null);
assert.equal(decodeBindings({ ...encoded, unknown: true }), null);
assert.equal(decodeBindings({ ...encoded, [`generation/${randomUUID()}`]: true }), null);
assert.equal(decodeBindings({ 'format/owner-publication-v1': true, 'published/hub': true }), null);
const event = { id: 'event', settlement: { status: 'confirmed' } } as LedgerEvent;
assert.equal(countConfirmedRegressions([event], []), 1);
assert.equal(countConfirmedRegressions([event], [event]), 0);
assert.equal(countConfirmedRegressions([event], [{ ...event, settlement: { ...event.settlement!, status: 'incomplete' } }]), 1);
assert.equal(decidePublication(before, before).publish, true, 'regression counts never gate publication');
console.log('publication input rule, closed checkpoint namespaces and diagnostic-only regression counts passed');
