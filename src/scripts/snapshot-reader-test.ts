import assert from 'node:assert/strict';
import { setTimeout as delay } from 'node:timers/promises';
import { createSnapshotReader } from '../api/snapshotReader';
import { ChainReadError } from '../data/dataSource';
import { fakeChainSource } from './support/fakeChainSource';
import { fixtureHead } from './support/chainFixture';
const errorCode = (code: string) => (error: unknown) => error instanceof ChainReadError && error.code === code;
async function main() {
  let heads=0,loads=0,states=0,lt='1',seqno=100;
  const source=fakeChainSource({head:async()=>{heads++;return fixtureHead(seqno);},getAccountState:async(_account,options)=>{
    states++;assert.equal(options?.at?.seqno,seqno);return{accountState:'active',balance:'0',lastTxLt:lt,lastTxHash:'a'.repeat(64)};
  }});
  const reader=createSnapshotReader(source);
  const load=async({head,signal}: {head:ReturnType<typeof fixtureHead>;signal:AbortSignal})=>{loads++;assert(!signal.aborted);await delay(5);return{value:loads,pinned:head.seqno};};
  const request={key:'one',deadlineMs:1000,load};
  const values=await Promise.all(Array.from({length:10},()=>reader.read(request)));
  assert.equal(loads,1);assert.equal(heads,1);assert(values.every(value=>value.asOfSeqno===100&&value.pinned===100));
  await reader.read(request);assert.equal(loads,2,'no completed-result reuse without an explicit policy');
  const reuse={...request,key:'account',reuse:{account:'owner',maxAgeMs:30_000}};
  await reader.read(reuse);const before=loads;seqno++;
  assert.equal((await reader.read(reuse)).asOfSeqno,100,'an unchanged current account reuses the honestly dated older result');
  assert.equal(loads,before);lt='2';assert.equal((await reader.read(reuse)).asOfSeqno,101);assert.equal(loads,before+1);assert.equal(states,3);
  const timed={...request,key:'time-only',reuse:{maxAgeMs:20}};
  await reader.read(timed);const headCount=heads;await reader.read(timed);assert.equal(heads,headCount);
  await delay(25);await reader.read(timed);assert.equal(heads,headCount+1);
  let underlying:AbortSignal|undefined, late!:()=>void;
  await assert.rejects(reader.read({key:'hanging',deadlineMs:15,load:async({signal})=>{underlying=signal;await new Promise<void>(resolve=>late=resolve);return{stale:true};}}),errorCode('upstream_timeout'));
  assert(underlying!.aborted,'the actual load receives cancellation');
  const replacement=await reader.read({...request,key:'hanging'});assert.equal(replacement.asOfSeqno,101);late();await delay(0);
  const afterLate=await reader.read({...request,key:'hanging'});assert(afterLate.value>replacement.value,'a late old completion cannot erase or populate its replacement');
  let sharedSignal:AbortSignal|undefined, release!:()=>void;
  const cancelOne=new AbortController();
  const shared={key:'shared',deadlineMs:1000,load:async({signal}: {signal:AbortSignal})=>{sharedSignal=signal;await new Promise<void>(resolve=>release=resolve);return{ok:true};}};
  const left=reader.read({...shared,signal:cancelOne.signal}),right=reader.read(shared);
  const leftRejected=assert.rejects(left,errorCode('upstream_unavailable'));
  await delay(0);cancelOne.abort();await leftRejected;assert.equal(sharedSignal!.aborted,false,'one cancelled consumer does not cancel the other');release();assert((await right).ok);
  const cancelAll=new AbortController();
  const abandoned=reader.read({...shared,key:'abandoned',signal:cancelAll.signal});
  const abandonedRejected=assert.rejects(abandoned,errorCode('upstream_unavailable'));
  await delay(0);cancelAll.abort();await abandonedRejected;assert(sharedSignal!.aborted,'last-consumer cancellation stops source work');release();
  assert((await reader.read({...request,key:'abandoned'})).asOfSeqno===101);
  // A short new caller has its own budget even when joining a longer flight.
  const long=reader.read({...shared,key:'joined-deadline'});await delay(0);
  await assert.rejects(reader.read({...shared,key:'joined-deadline',deadlineMs:10}),errorCode('upstream_timeout'));
  assert.equal(sharedSignal!.aborted,false);release();await long;
  let headSignal:AbortSignal|undefined;
  const stalledHead=createSnapshotReader(fakeChainSource({head:async({signal}={})=>{headSignal=signal;return new Promise(()=>{});}}));
  await assert.rejects(stalledHead.read({...request,deadlineMs:10}),errorCode('upstream_timeout'));assert(headSignal!.aborted);
  const bounded=createSnapshotReader(source), controllers=Array.from({length:128},()=>new AbortController());
  const pending=controllers.map((controller,index)=>bounded.read({key:`bounded-${index}`,deadlineMs:1000,signal:controller.signal,load:async()=>new Promise<object>(()=>{})}).catch(error=>error));
  await assert.rejects(bounded.read({...request,key:'overflow'}),errorCode('upstream_unavailable'));
  controllers.forEach(controller=>controller.abort());
  assert((await Promise.all(pending)).every(error=>error instanceof ChainReadError));
  assert((await bounded.read({...request,key:'recovered-capacity'})).asOfSeqno===101);
  let savedLoads=0;
  const cacheLoad=async()=>({value:++savedLoads});
  for(let index=0;index<129;index++)await bounded.read({key:`cache-${index}`,deadlineMs:1000,reuse:{maxAgeMs:30_000},load:cacheLoad});
  await bounded.read({key:'cache-128',deadlineMs:1000,reuse:{maxAgeMs:30_000},load:cacheLoad});assert.equal(savedLoads,129);
  await bounded.read({key:'cache-0',deadlineMs:1000,reuse:{maxAgeMs:30_000},load:cacheLoad});assert.equal(savedLoads,130,'completed reuse has a bounded LRU');
  console.log('Snapshot reader single flight, explicit account/time reuse, pinned sequence, real aborts, hanging head/load recovery, late completion fencing and independent consumer deadlines passed.');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
